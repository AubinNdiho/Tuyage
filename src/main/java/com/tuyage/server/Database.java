    ChatMessage updateCallStatus(String callId, String status) throws SQLException {
        if (callId == null || callId.isBlank()) return null;
        long now = System.currentTimeMillis();
        try (Connection c = c()) {
            long acceptedAt = 0;
            try (PreparedStatement q = c.prepareStatement("SELECT call_accepted_at FROM messages WHERE call_id=? ORDER BY id DESC LIMIT 1")) {
                q.setString(1, callId); try (ResultSet rs = q.executeQuery()) { if (!rs.next()) return null; acceptedAt = rs.getLong(1); }
            }
            long duration = acceptedAt > 0 ? Math.max(0, (now - acceptedAt) / 1000L) : 0L;
            if ("ONGOING".equals(status)) {
                try (PreparedStatement ps = c.prepareStatement("UPDATE messages SET call_status=?,call_accepted_at=?,call_duration_seconds=0 WHERE call_id=?")) {
                    ps.setString(1, status); ps.setLong(2, now); ps.setString(3, callId); ps.executeUpdate();
                }
            } else {
                try (PreparedStatement ps = c.prepareStatement("UPDATE messages SET call_status=?,call_duration_seconds=? WHERE call_id=?")) {
                    ps.setString(1, status == null ? "" : status); ps.setLong(2, duration); ps.setString(3, callId); ps.executeUpdate();
                }
            }
        }
        return getCallMessage(callId);
    }

